#!/usr/bin/env bash
# Purpose: Publish the machine's current IP address where the UI/display can
#          show it (issue #416). Writes the addresses into a Klipper include
#          (~/printer_data/config/network.cfg) as gcode_macro variables and
#          emits a Moonraker-friendly marker, then reloads Klipper settings.
#
# Run at boot and on network changes (NetworkManager dispatcher) so the IP is
# always current. Idempotent and safe to run repeatedly.

set -euo pipefail

CONFIG_DIR="${HOME}/printer_data/config"
NET_CFG="${CONFIG_DIR}/network.cfg"

# Collect IPv4 addresses, preferring the default-route interface first.
primary_iface="$(ip route show default 2>/dev/null | awk '/default/ {print $5; exit}')"
mapfile -t addrs < <(
  {
    if [[ -n "$primary_iface" ]]; then
      ip -4 -o addr show dev "$primary_iface" 2>/dev/null | awk '{print $4}' | cut -d/ -f1
    fi
    ip -4 -o addr show 2>/dev/null | awk '{print $4}' | cut -d/ -f1
  } | grep -v '^127\.' | awk '!seen[$0]++'
)

ip_primary="${addrs[0]:-unavailable}"
ip_all="$(IFS=', '; echo "${addrs[*]:-unavailable}")"

mkdir -p "$CONFIG_DIR"
{
  echo "# Auto-generated by neo9labs-ip-publish.sh — do not edit."
  echo "# Shows the printer IP in Klipper/Fluidd/Mainsail and on the display."
  echo "[gcode_macro _NET_INFO]"
  echo "variable_ip: \"${ip_primary}\""
  echo "variable_all_ips: \"${ip_all}\""
  echo ""
  echo "[gcode_macro SHOW_IP]"
  echo "description: Print the printer's IP address(es) to the console"
  echo "gcode:"
  echo "  {action_respond_info(\"Printer IP: \" + _NET_INFO.ip)}"
  echo "  M117 {\"IP: \" + _NET_INFO.ip}"
} > "$NET_CFG.tmp"
mv "$NET_CFG.tmp" "$NET_CFG"

echo "[ip-publish] IP(s): ${ip_all} (primary: ${ip_primary}) -> ${NET_CFG}"
